"""The librpc client for Python (asyncio): one connection carries any number of concurrent calls.

    rpc = await RpcClient.connect("ws://localhost:8080/rpc", token="secret")
    calc = CalcClient(rpc)                               # generated by rpcc --py
    print(await calc.add(40, 2))
    async with calc.count(1, 5) as ticks:                # leaving the block cancels the stream
        async for tick in ticks:
            print(tick.label)
    await rpc.close()

When the connection is lost every call fails with RpcError(Code.Unavailable); connect again to continue.
"""

import asyncio
import enum
from collections import deque

from bufs import message_size

from . import rpc_bufs as wire
from .websocket import HandshakeError, WebSocket

SUBPROTOCOL = "librpc.v1"


class Code(enum.IntEnum):
    Ok = 0
    Cancelled = 1
    Unknown = 2
    InvalidArgument = 3
    DeadlineExceeded = 4
    NotFound = 5
    AlreadyExists = 6
    PermissionDenied = 7
    ResourceExhausted = 8
    FailedPrecondition = 9
    Aborted = 10
    OutOfRange = 11
    Unimplemented = 12
    Internal = 13
    Unavailable = 14
    DataLoss = 15
    Unauthenticated = 16


def _code(value):
    try:
        return Code(value)
    except ValueError:
        return value


class RpcError(Exception):
    """A call that did not end in Ok. `detail` is the application-defined detail of the status (0 = none)."""

    def __init__(self, code, message="", detail=0):
        code = _code(code)
        name = code.name if isinstance(code, Code) else str(code)
        super().__init__(f"{name}: {message}" if message else name)
        self.code = code
        self.message = message
        self.detail = detail


class _Call:
    __slots__ = ("id", "decode", "decode_trailer", "future", "stream", "timer")

    def __init__(self, id, decode):
        self.id = id
        self.decode = decode
        self.decode_trailer = None
        self.future = None
        self.stream = None
        self.timer = None


class RpcStream:
    """A call whose items are read with `async for`: server streaming, and the answer side of bidirectional calls.
    `send()` / `end()` / `finish()` serve client streaming. Leave the loop early with `cancel()` (or `async with`)."""

    def __init__(self, client, id):
        self._client = client
        self._id = id
        self._items = deque()
        self._waiting = None
        self._error = None
        self._ended = False
        self.trailer = None
        """The closing message of a stream whose method declares a trailer; set once the iteration has ended."""

    async def send(self, message):
        """Sends one item (a finished message of the method's item type), waiting while the server has not read enough of
        what is already sent. Returns False when the call is over (the server answered, or it was cancelled): stop sending."""
        return await self._client._send_item(self._id, message)

    def end(self):
        """Says that no more items will be sent."""
        self._client._end_items(self._id)

    async def finish(self):
        """Client streaming: ends the items, waits for the answer and returns it (the trailer); raises if the call failed."""
        self.end()
        async for _ in self:
            pass
        return self.trailer

    def cancel(self):
        self._client._cancel_call(self._id, RpcError(Code.Cancelled, "cancelled"))

    def __aiter__(self):
        return self

    async def __anext__(self):
        if self._items:
            value, frame_bytes = self._items.popleft()
            self._client._consumed(frame_bytes, not self._items)
            return value
        if self._ended:
            if self._error:
                raise self._error
            raise StopAsyncIteration
        self._waiting = asyncio.get_running_loop().create_future()
        try:
            return await self._waiting
        except asyncio.CancelledError:
            self.cancel()
            raise

    async def aclose(self):
        self.cancel()

    async def __aenter__(self):
        return self

    async def __aexit__(self, *exc):
        self.cancel()


class RpcUpload:
    """A client-streaming call: `await send(item)`, then `await finish()` for the answer."""

    def __init__(self, stream, encode):
        self._stream = stream
        self._encode = encode

    async def send(self, item):
        return await self._stream.send(self._encode(item))

    async def finish(self):
        return await self._stream.finish()

    def cancel(self):
        self._stream.cancel()


class RpcDuplex:
    """A bidirectional call: `send` and `end` on one side, `async for` on the other (they may run concurrently)."""

    def __init__(self, stream, encode):
        self._stream = stream
        self._encode = encode

    async def send(self, item):
        return await self._stream.send(self._encode(item))

    def end(self):
        self._stream.end()

    def cancel(self):
        self._stream.cancel()

    def __aiter__(self):
        return self._stream.__aiter__()

    async def __aenter__(self):
        return self

    async def __aexit__(self, *exc):
        self.cancel()


class RpcClient:
    def __init__(self, ws, window, ping_interval):
        self._ws = ws
        self._window = window
        self._ping_interval = ping_interval
        self._next_id = 1
        self._calls = {}
        self._unreported = 0
        self._closed_with = None
        self._server_max_message = 0
        self._send_unacked = 0
        self._credit_waiters = []
        self._tasks = []
        self.server_name = ""
        self.session_id = 0

    @classmethod
    async def connect(cls, url, *, token=None, peer="librpc-py/0.1", window=1 << 20, max_message=16 << 20, ping_interval=15.0,
                      connect_timeout=10.0, ssl=None, headers=None):
        """Connects, says Hello and waits for the Welcome. Raises RpcError."""
        try:
            ws = await asyncio.wait_for(WebSocket.connect(url, SUBPROTOCOL, headers, ssl, max_message), connect_timeout)
        except asyncio.TimeoutError:
            raise RpcError(Code.DeadlineExceeded, "connect timed out") from None
        except HandshakeError as e:
            code = {401: Code.Unauthenticated, 403: Code.PermissionDenied}.get(e.status, Code.Unavailable)
            raise RpcError(code, str(e)) from None
        except (OSError, ValueError) as e:
            raise RpcError(Code.Unavailable, f"cannot connect to {url}: {e}") from None
        client = cls(ws, window, ping_interval)
        ws.send_nowait(wire.Envelope.encode(kind=wire.Kind.Hello, protocol=1, peer=peer, token=token or "", window=window,
                                            max_message=max_message))
        try:
            first = await asyncio.wait_for(ws.recv(), connect_timeout)
        except asyncio.TimeoutError:
            await ws.close()
            raise RpcError(Code.DeadlineExceeded, "no Welcome from the server") from None
        if first is None:
            raise RpcError(Code.Unavailable, f"connection closed ({ws.close_code}) {ws.close_reason}".strip())
        env = wire.Envelope.decode(first)
        if env.kind == wire.Kind.End:
            await ws.close()
            raise RpcError(env.code, env.message, env.detail)
        if env.kind != wire.Kind.Welcome:
            await ws.close()
            raise RpcError(Code.DataLoss, "expected Welcome")
        client.server_name = env.peer
        client.session_id = env.session
        if env.window:
            client._window = env.window
        client._server_max_message = env.max_message
        client._tasks.append(asyncio.create_task(client._read_loop()))
        if ping_interval and ping_interval > 0:
            client._tasks.append(asyncio.create_task(client._ping_loop()))
        return client

    @property
    def connected(self):
        return self._closed_with is None and not self._ws.closed

    async def close(self):
        """Ends every running call with Unavailable and closes the connection."""
        self._lost(RpcError(Code.Unavailable, "client closed"))
        await self._ws.close(1000, "bye")
        for task in self._tasks:
            task.cancel()
        for task in self._tasks:
            try:
                await task
            except (asyncio.CancelledError, Exception):
                pass

    async def __aenter__(self):
        return self

    async def __aexit__(self, *exc):
        await self.close()

    # ---- calls --------------------------------------------------------------------------------------------

    async def call(self, method, request, decode, *, timeout=None):
        """A unary call: `request` is a finished message, `decode` reads the response (e.g. `Value.decode`)."""
        future = asyncio.get_running_loop().create_future()
        call = self._begin(method, request, decode, timeout, future)
        try:
            return await future
        except asyncio.CancelledError:
            if call is not None:
                self._cancel_call(call.id, RpcError(Code.Cancelled, "cancelled"))
            raise

    def stream(self, method, request, decode, *, timeout=None, decode_trailer=None):
        """A server-streaming call (and, with `send`/`end`, the client-streaming and bidirectional ones). Errors surface
        from the iteration."""
        id = self._take_id()
        stream = RpcStream(self, id)
        call = self._begin(method, request, decode, timeout, None, id, stream)
        if call is not None:
            call.decode_trailer = decode_trailer
        return stream

    def _take_id(self):
        id = self._next_id
        self._next_id = self._next_id + 1 if self._next_id < 0xFFFFFFFF else 1
        return id

    def _begin(self, method, request, decode, timeout, future, id=None, stream=None):
        def fail(error):
            if stream is not None:
                stream._ended = True
                stream._error = error
            elif not future.done():
                future.set_exception(error)

        if id is None:
            id = self._take_id()
        if self._closed_with is not None:
            fail(self._closed_with)
            return None
        deadline_ms = int(timeout * 1000) if timeout else 0
        envelope = wire.Envelope.encode(id=id, kind=wire.Kind.Call, method=method, deadline_ms=deadline_ms)
        if self._server_max_message and len(envelope) + len(request) > self._server_max_message:
            fail(RpcError(Code.ResourceExhausted, "request exceeds the server's maximum message size"))
            return None
        call = _Call(id, decode)
        call.future = future
        call.stream = stream
        self._calls[id] = call
        if timeout and timeout > 0:
            call.timer = asyncio.get_running_loop().call_later(
                timeout, self._cancel_call, id, RpcError(Code.DeadlineExceeded, "deadline exceeded"))
        try:
            self._ws.send_nowait(envelope + request)
        except Exception as e:
            self._finish(call, RpcError(Code.Unavailable, str(e)))
            return None
        return call

    def _cancel_call(self, id, error):
        call = self._calls.get(id)
        if call is None:
            return
        try:
            self._ws.send_nowait(wire.Envelope.encode(id=id, kind=wire.Kind.Cancel))
        except Exception:
            pass
        self._finish(call, error)

    async def _send_item(self, id, message):
        envelope = wire.Envelope.encode(id=id, kind=wire.Kind.Data)
        frame_bytes = len(envelope) + len(message)
        if self._server_max_message and frame_bytes > self._server_max_message:
            raise RpcError(Code.ResourceExhausted, "stream item exceeds the server's maximum message size")
        while id in self._calls and self._closed_with is None and self._send_unacked > 0 and self._send_unacked + frame_bytes > self._window:
            waiter = asyncio.get_running_loop().create_future()
            self._credit_waiters.append(waiter)
            await waiter
        if id not in self._calls or self._closed_with is not None:
            return False
        self._send_unacked += frame_bytes
        try:
            self._ws.send_nowait(envelope + message)
            await self._ws.drain()
        except Exception:
            return False
        return True

    def _end_items(self, id):
        if id not in self._calls:
            return
        try:
            self._ws.send_nowait(wire.Envelope.encode(id=id, kind=wire.Kind.End))
        except Exception:
            pass

    def _wake_senders(self):
        waiting, self._credit_waiters = self._credit_waiters, []
        for waiter in waiting:
            if not waiter.done():
                waiter.set_result(None)

    def _consumed(self, frame_bytes, drained=False):
        """Items the caller consumed (or that were dropped): report them once a quarter window has piled up."""
        self._unreported += frame_bytes
        if drained or self._unreported >= max(1, self._window // 4):
            credit, self._unreported = self._unreported, 0
            try:
                self._ws.send_nowait(wire.Envelope.encode(kind=wire.Kind.Credit, credit=credit))
            except Exception:
                pass

    # ---- incoming -----------------------------------------------------------------------------------------

    async def _read_loop(self):
        try:
            while True:
                data = await self._ws.recv()
                if data is None:
                    self._lost(RpcError(Code.Unavailable, f"connection closed ({self._ws.close_code}) {self._ws.close_reason}".strip()))
                    return
                self._on_frame(data)
        except asyncio.CancelledError:
            raise
        except Exception as e:  # a bug must not leave callers waiting forever
            self._lost(RpcError(Code.Internal, f"client failure: {e!r}"))

    async def _ping_loop(self):
        while True:
            await asyncio.sleep(self._ping_interval)
            try:
                self._ws.send_nowait(wire.Envelope.encode(kind=wire.Kind.Ping))
            except Exception:
                return

    def _on_frame(self, data):
        try:
            env = wire.Envelope.decode(data)
            size = message_size(data)
            body = memoryview(data)[size:] if size < len(data) else None
        except Exception:
            self._lost(RpcError(Code.DataLoss, "malformed frame from server"))
            asyncio.ensure_future(self._ws.close(1002, "malformed frame"))
            return
        kind = env.kind
        if kind == wire.Kind.Data:
            call = self._calls.get(env.id)
            if call is None or call.stream is None or body is None:
                self._consumed(len(data))  # the server still counts these bytes
                return
            try:
                value = call.decode(body)
            except Exception:
                self._cancel_call(env.id, RpcError(Code.DataLoss, "malformed stream item"))
                return
            stream = call.stream
            if stream._waiting is not None and not stream._waiting.done():
                waiting, stream._waiting = stream._waiting, None
                waiting.set_result(value)
                self._consumed(len(data))
            else:
                stream._items.append((value, len(data)))
        elif kind == wire.Kind.End:
            if env.id == 0:
                self._lost(RpcError(env.code, env.message, env.detail))
                return
            call = self._calls.get(env.id)
            if call is None:
                return
            if env.code != Code.Ok:
                self._finish(call, RpcError(env.code, env.message, env.detail))
            elif call.stream is not None:
                if body is not None and call.decode_trailer is not None:
                    try:
                        call.stream.trailer = call.decode_trailer(body)
                    except Exception:
                        self._finish(call, RpcError(Code.DataLoss, "malformed trailer"))
                        return
                self._finish(call)
            elif body is None:
                self._finish(call, RpcError(Code.DataLoss, "the server sent no response"))
            else:
                try:
                    value = call.decode(body)
                except Exception:
                    self._finish(call, RpcError(Code.DataLoss, "malformed response"))
                    return
                self._finish(call, None, value)
        elif kind == wire.Kind.Credit:
            self._send_unacked = max(0, self._send_unacked - env.credit)
            self._wake_senders()
        elif kind == wire.Kind.Closing:
            self._closed_with = RpcError(Code.Unavailable, "server is shutting down")

    def _finish(self, call, error=None, value=None):
        """Ends one call: an error, a unary result, or (neither) the clean end of a stream."""
        self._calls.pop(call.id, None)
        self._wake_senders()
        if call.timer is not None:
            call.timer.cancel()
        stream = call.stream
        if stream is not None:
            stream._ended = True
            stream._error = error
            if error:
                for _, frame_bytes in stream._items:  # what was queued is dropped; its bytes still count against the window
                    self._consumed(frame_bytes)
                stream._items.clear()
            waiting, stream._waiting = stream._waiting, None
            if waiting is not None and not waiting.done():
                if error:
                    waiting.set_exception(error)
                else:
                    waiting.set_exception(StopAsyncIteration())
        elif call.future is not None and not call.future.done():
            if error:
                call.future.set_exception(error)
            else:
                call.future.set_result(value)

    def _lost(self, error):
        if self._closed_with is not None and self._closed_with.code == Code.Unavailable and not self._calls:
            return
        if self._closed_with is None:
            self._closed_with = error
        self._ws.closed = True
        for call in list(self._calls.values()):
            self._finish(call, error)

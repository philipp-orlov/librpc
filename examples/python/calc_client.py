"""A Python client for calc_server (asyncio): the same calls as the C++, C# and TypeScript examples.

    python3 examples/python/calc_client.py [ws://127.0.0.1:8080/rpc] [token]

The Python for the schema is made with rpcc (once, or at build time):  rpcc --no-cpp --py -o examples/python/gen examples/calc.bufs
It needs the `bufs` runtime (libbufs/python) and `librpc` (librpc/python) on sys.path; this script adds both when run from a
checkout. No third-party packages.
"""

import asyncio
import os
import sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
for path in (os.path.join(root, "python"), os.path.join(root, "..", "libbufs", "python"), os.path.join(root, "examples", "python", "gen")):
    sys.path.insert(0, path)

from calc_bufs import CalcClient, Point  # noqa: E402  (generated by rpcc --py)
from librpc import Code, RpcClient, RpcError  # noqa: E402


async def main():
    url = sys.argv[1] if len(sys.argv) > 1 else "ws://127.0.0.1:8080/rpc"
    token = sys.argv[2] if len(sys.argv) > 2 else None
    async with await RpcClient.connect(url, token=token) as rpc:
        calc = CalcClient(rpc)

        print(f"40 + 2 = {await calc.add(40, 2):g}")
        print(f"sum = {await calc.sum([1.5, 2.5, 3.0, 4.0]):g}")
        print(f"echo: '{await calc.echo('hello, rpc')}'")
        print(f"path = {await calc.path_length(Point(x=0, y=0), [Point(x=3, y=0), Point(x=3, y=4)]):g}")

        async for tick in calc.count(1, 5):  # a server stream: items arrive as the server makes them
            print(f"  {tick.label}")

        total = calc.total()  # client streaming: send many items, then ask for the answer
        for i in range(1, 101):
            await total.send(i)
        print(f"total = {await total.finish():g}")

        async with calc.running() as running:  # bidirectional: each answer follows its question
            answers = running.__aiter__()
            line = "running:"
            for value in (1.0, 2.0, 3.0, 4.0):
                await running.send(value)
                line += f" {await answers.__anext__():g}"
            print(line)
            running.end()

        upload = calc.upload("blob")  # a client stream with a parameter in the call itself
        for _ in range(16):
            await upload.send({"data": bytes([7]) * 4096})
        print(f"upload = {await upload.finish()}")

        try:
            await calc.div(1, 0, timeout=5)
        except RpcError as e:
            print(f"expected failure: {Code(e.code).name}")


asyncio.run(main())
